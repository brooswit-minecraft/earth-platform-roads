package io.github.brooswitminecraft.earthplatformroads.mixin;

import io.earthplatform.minecraft.cubic.earth.EarthGenerator;
import io.earthplatform.minecraft.cubic.gen.SurfaceGenerator;
import io.github.brooswitminecraft.earthplatformroads.compat.layeredslopes.LayeredSlopesCompat;
import io.github.brooswitminecraft.earthplatformroads.road.RoadNetwork;
import io.github.brooswitminecraft.earthplatformroads.road.RoadSegment;
import io.github.brooswitminecraft.earthplatformroads.road.RoadSurfaceLayering;
import io.github.brooswitminecraft.earthplatformroads.road.RoadSurfaceMaterial;
import io.github.brooswitminecraft.earthplatformroads.road.RoadSurfaceRendering;
import io.github.brooswitminecraft.layeredslopes.LayeredBlock;
import net.minecraft.world.level.block.state.BlockState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

/**
 * The mod's whole seam into generation: {@link EarthGenerator} is {@code final} and ships no
 * extension point, so a column's cover is overridden after the fact at the one place it is decided
 * -- {@code surface(int,int,int,int,int)}, called once per column by both near-cube generation
 * ({@link SurfaceGenerator#terrain}) and far-LOD generation. Overriding it here, rather than cube
 * contents after the fact, means a road column gets no trees, grass or flowers in the first place
 * instead of having them grown and then removed, and automatically gets the same cave/ore/strata
 * treatment under it as any other column -- only the top few blocks and vegetation eligibility
 * change.
 *
 * <p>Ground height, water and biome are left untouched: no cuttings, embankments, bridges or
 * tunnels are generated by this mixin (see {@link RoadNetwork} for which mapped features are
 * excluded -- e.g. bridges, tracked but never rendered as a crossing).
 *
 * <p>Top surface at a step between two same-road columns uses {@link LayeredSlopesCompat}'s
 * polished-blackstone {@link LayeredBlock} with a layer count from {@link RoadSurfaceLayering},
 * instead of this mod's previous always-full {@code POLISHED_BLACKSTONE}: see MINECRAFT-566,
 * John's playtest finding that whole-block stairs on a grade are not acceptable, and the ticket
 * comments' two-round back-and-forth on exactly how to pick that layer count (see
 * {@link RoadSurfaceLayering}'s class doc for that history) -- this mixin now scans outward up to
 * {@link RoadSurfaceLayering#MAX_NEIGHBOR_DISTANCE} same-road columns in each of 4 directions for
 * the nearest column with a lower ground height, and decays this column's own layer count by that
 * distance, rather than comparing only immediate neighbors (which left a new, almost-as-bad gap one
 * column past the actual step).
 *
 * <p>MINECRAFT-566's road-styling ask (comment 55484, John's live-playtest feedback: roads read as
 * too narrow, wants a yellow centerline and gravel shoulders): the material painted now depends on
 * {@link RoadSegment#crossSectionAt} -- {@code CENTERLINE} (thin, astride the centerline, classes
 * that opt in only) paints {@link LayeredSlopesCompat#LAYERED_YELLOW_TERRACOTTA} over a blackstone
 * {@code under()} (a painted line ON pavement, not a full-depth material change); {@code PAVED}
 * paints blackstone exactly as before; {@code SHOULDER} (the new narrow band outside the paved
 * edge) paints {@link LayeredSlopesCompat#LAYERED_GRAVEL} over a gravel {@code under()} (gravel the
 * whole way down a few layers, like a real shoulder, not pavement with a gravel skin) -- never
 * vanilla falling gravel, since {@code LayeredBlock} extends plain {@code Block}, not
 * {@code FallingBlock} (confirmed by reading the class). The SAME {@link RoadSurfaceLayering} decay
 * applies to every zone's material, so the slope-layering continuity this mixin already provides
 * for blackstone carries over to the centerline and shoulder too, not just the paved surface.
 * {@code under()} always stays a full block (never layered) because {@code EarthGenerator} uses it
 * at depths 1-3 under the column, per the ticket's explicit instruction.
 */
@Mixin(EarthGenerator.class)
public abstract class EarthGeneratorRoadMixin {
    @Inject(
            method = "surface(IIIII)Lio/earthplatform/minecraft/cubic/gen/SurfaceGenerator$Surface;",
            at = @At("RETURN"),
            cancellable = true)
    private void earthplatformroads$overlayRoad(
            int x, int z, int y, int water, int slope, CallbackInfoReturnable<SurfaceGenerator.Surface> cir) {
        // A column already under water (a lake, a river, the sea) never becomes road surface: this
        // mixin paints an at-grade road, not a causeway or ford.
        if (water != SurfaceGenerator.DRY && water >= y) return;
        EarthGenerator self = (EarthGenerator) (Object) this;
        // MINECRAFT-586: one scoped cache for this single column's whole surface() call, including
        // the up-to-120-lookup ring scan below -- see RoadNetwork.ScopedLookupCache's own doc for why
        // reusing it only within this one synchronous call carries no staleness risk.
        RoadNetwork.ScopedLookupCache cache = RoadNetwork.freshScopedLookupCache();
        RoadSegment segment = RoadNetwork.segmentCoveringColumn(self.grid(), x, z, cache);
        if (segment == null) return;
        RoadSegment.CrossSection crossSection = segment.crossSectionAt(self.grid(), x, z);
        if (crossSection == RoadSegment.CrossSection.OFF_ROAD) return; // excluded (bridge/tunnel) way's own footprint check already ran in segmentCoveringColumn
        SurfaceGenerator.Surface original = cir.getReturnValue();
        int distance = nearestLowerSameRoadDistance(self, segment, x, z, y, cache);
        int layers = RoadSurfaceLayering.layersForNearestLowerNeighbor(distance);
        RoadSurfaceMaterial material = RoadSurfaceMaterial.fromOsmSurfaceTag(segment.surface());
        BlockState under = RoadSurfaceRendering.underSurfaceFor(crossSection, material);
        BlockState top = RoadSurfaceRendering.topSurfaceFor(crossSection, layers, material);
        cir.setReturnValue(new SurfaceGenerator.Surface(original.biome(), top, under, 0, 0, 0, 0, 0, false));
    }

    /**
     * Distance, in columns (Chebyshev / chessboard distance, so a diagonal neighbor at offset
     * (1,1) counts as distance 1, not ~1.4), to the nearest same-road (by stable {@code wayId})
     * neighbor with a lower ground height, searching outward one full ring at a time up to
     * {@link RoadSurfaceLayering#MAX_NEIGHBOR_DISTANCE}; {@code 0} if none is found that close.
     *
     * <p>Scanning only the 4 axis-aligned offsets at each distance (as an earlier version of this
     * method did) missed a lower neighbor reachable only diagonally, which broke the one property
     * this whole scheme depends on: two columns one step apart must get distances that differ by
     * at most 1 (so their decayed layer counts, and therefore their collision tops, stay close).
     * Scanning the full ring (every cell at exactly this Chebyshev distance, {@code (2d+1)^2 -
     * (2d-1)^2} of them) is what actually guarantees that -- a real regression John's review caught
     * (a diagonal feature made one column drop sharply while its immediate neighbor, which could
     * not see that same feature within its own axis-only scan, stayed full).
     *
     * <p>A neighbor just outside the road's half-width, or on a different mapped way, is natural
     * terrain or someone else's road, neither of which this column's own surface should try to
     * match.
     */
    private static int nearestLowerSameRoadDistance(
            EarthGenerator self, RoadSegment segment, int x, int z, int y, RoadNetwork.ScopedLookupCache cache) {
        var grid = self.grid();
        for (int distance = 1; distance <= RoadSurfaceLayering.MAX_NEIGHBOR_DISTANCE; distance++) {
            for (int ddx = -distance; ddx <= distance; ddx++) {
                for (int ddz = -distance; ddz <= distance; ddz++) {
                    if (Math.max(Math.abs(ddx), Math.abs(ddz)) != distance) continue; // only this ring, not the filled square
                    int nx = x + ddx, nz = z + ddz;
                    RoadSegment neighborSegment = RoadNetwork.segmentCoveringColumn(grid, nx, nz, cache);
                    if (neighborSegment == null || neighborSegment.wayId() != segment.wayId()) continue;
                    if (self.surfaceY(nx, nz) < y) return distance;
                }
            }
        }
        return 0;
    }
}
